export function getRewardById(rewardId) {
  return rewardCatalog.find((reward) => reward.id === rewardId);
}

export function getRewardsByAchievementId(achievementId) {
  return rewardCatalog.filter(
    (reward) =>
      reward.requirement.type === 'achievement' &&
      reward.requirement.achievementId === achievementId,
  );
}

export function canUnlockReward(reward, player) {
  if (!reward) {
    return false;
  }

  if (reward.requirement.type === 'points') {
    return player.points >= reward.requirement.points;
  }

  if (reward.requirement.type === 'achievement') {
    return getUnlockedAchievementIds(player).has(reward.requirement.achievementId);
  }

  return false;
}

export function getRewardCards(player) {
  const ownedRewardIds = new Set(player.ownedRewardIds || []);

  return rewardCatalog.map((reward) => ({
    ...reward,
    unlocked: canUnlockReward(reward, player),
    owned: ownedRewardIds.has(reward.id),
    equipped: player.equippedRewardId === reward.id,
  }));
}
